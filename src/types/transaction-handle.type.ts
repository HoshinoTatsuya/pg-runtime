/**
 * Что отличает транзакцию Drizzle от корневого клиента: `rollback()`. Работа,
 * объявившая параметром корневой клиент (`NodePgDatabase`), — ошибка
 * компиляции, а не запись автокоммитом мимо транзакции вызывающего.
 *
 * Описано структурно по той же причине, что `PoolDatabase`: тип транзакции
 * выводится из работы ПРОЕКТА, и сравнивать его с классом Drizzle пакета
 * нельзя — компилятор с несведёнными симлинками счёл бы их разными.
 */
export interface TransactionHandle {
  rollback(): never;
}
