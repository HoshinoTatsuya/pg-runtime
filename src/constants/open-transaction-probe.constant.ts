/**
 * Осталась ли на соединении открытая транзакция: `now()` — начало транзакции,
 * `statement_timestamp()` — начало оператора. В неявной транзакции одного
 * оператора они равны, внутри `BEGIN` — нет. Запрос обязан идти БЕЗ
 * параметров, то есть простым протоколом: по расширенному (Parse/Bind/Execute)
 * они различаются и вне транзакции — замер 2000 ложных «в транзакции» из 2000
 * против 0 из 2000 простым протоколом и 0 пропусков из 1000 сразу после BEGIN.
 */
export const OPEN_TRANSACTION_PROBE_SQL = 'SELECT now() <> statement_timestamp() AS in_tx';
